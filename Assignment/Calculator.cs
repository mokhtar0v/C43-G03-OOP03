using System;
using System.Collections.Generic;
using System.Linq;
using System.Text;
using System.Threading.Tasks;

namespace Assignment
{
    internal class Calculator
    {
        public int sum(int x, int y)
        {
            return x + y;
        }
        public double sum(double x, double y)
        {
            return x + y;
        }
        public int sum(int x, int y, int z)
        {
            return x + y + z;
        }
    }
